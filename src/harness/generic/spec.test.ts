import { describe, it, expect } from "vitest";
import { mappingsFor, pgTableName, postgresDdl, postgresType, snake, sqlServerDdl, sqlServerType } from "./spec.js";
import type { ColType, ObjectSpec, TableSpec } from "./spec.js";
import { MIN_NON_EMPTY_FRACTION, vacuityFailure, withTableValuedArgs } from "./run.js";

describe("type mapping", () => {
  const cases: Array<[ColType, string, string]> = [
    [{ kind: "int" }, "int", "integer"],
    [{ kind: "tinyint" }, "tinyint", "smallint"],
    [{ kind: "bigint" }, "bigint", "bigint"],
    [{ kind: "money" }, "money", "numeric(19,4)"],
    [{ kind: "datetime" }, "datetime", "timestamp(3)"],
    [{ kind: "datetime2" }, "datetime2(7)", "timestamp"],
    [{ kind: "date" }, "date", "date"],
    [{ kind: "decimal", p: 18, s: 3 }, "decimal(18,3)", "numeric(18,3)"],
    [{ kind: "nvarchar", n: 50 }, "nvarchar(50)", "varchar(50)"],
    [{ kind: "char", n: 3 }, "char(3)", "char(3)"],
    [{ kind: "bit" }, "bit", "boolean"],
    [{ kind: "geography" }, "geography", "geography"],
    [{ kind: "varbinary" }, "varbinary(max)", "bytea"],
  ];
  it.each(cases)("%o -> %s / %s", (t, ss, pg) => {
    expect(sqlServerType(t)).toBe(ss);
    expect(postgresType(t)).toBe(pg);
  });
});

describe("naming", () => {
  it("snake-cases table names for PostgreSQL", () => {
    expect(snake("StockItemHoldings")).toBe("stock_item_holdings");
    expect(pgTableName({ schema: "Warehouse", name: "StockItems" })).toBe("warehouse.stock_items");
  });
});

describe("DDL", () => {
  const t: TableSpec = {
    schema: "Sales", name: "OrderLines",
    columns: [
      { name: "OrderLineID", type: { kind: "int" }, role: "pk" },
      { name: "Description", type: { kind: "nvarchar", n: 100 } },
      { name: "UnitPrice", type: { kind: "decimal", p: 18, s: 2 }, nullable: true },
    ],
  };
  it("SQL Server table: bracketed names, nullability, primary key", () => {
    const ddl = sqlServerDdl(t);
    expect(ddl).toContain("CREATE TABLE [Sales].[OrderLines]");
    expect(ddl).toContain("[Description] nvarchar(100) NOT NULL");
    expect(ddl).toContain("[UnitPrice] decimal(18,2) NULL");
    expect(ddl).toContain("PRIMARY KEY ([OrderLineID])");
  });
  it("PostgreSQL table: quoted names keep their case, nullable columns have no constraint", () => {
    const ddl = postgresDdl(t);
    expect(ddl).toContain("CREATE TABLE sales.order_lines");
    expect(ddl).toContain('"Description" varchar(100) NOT NULL');
    expect(ddl).toMatch(/"UnitPrice" numeric\(18,2\)(,|\n)/);
    expect(ddl).toContain('PRIMARY KEY ("OrderLineID")');
  });
  it("identity columns", () => {
    const id: TableSpec = { schema: "s", name: "t", columns: [{ name: "Id", type: { kind: "int" }, identity: true }] };
    expect(sqlServerDdl(id)).toContain("[Id] int IDENTITY(1,1) NOT NULL");
    expect(postgresDdl(id)).toContain('"Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL');
  });
  it("table-valued parameter types and memory-optimized objects", () => {
    const tvp: TableSpec = { schema: "Website", name: "L", tvp: { argIndex: 0 }, memoryOptimized: {}, columns: [{ name: "Id", type: { kind: "int" }, role: "pk" }] };
    expect(sqlServerDdl(tvp)).toMatch(/^CREATE TYPE \[Website\]\.\[L\] AS TABLE[\s\S]*PRIMARY KEY NONCLUSTERED \(\[Id\]\)[\s\S]*WITH \(MEMORY_OPTIMIZED = ON\)$/);
    const mo: TableSpec = { schema: "W", name: "C", memoryOptimized: { index: ["S"] }, columns: [{ name: "S", type: { kind: "int" } }] };
    expect(sqlServerDdl(mo)).toContain("INDEX [ix_C_S] NONCLUSTERED ([S])");
    expect(sqlServerDdl(mo)).toContain("WITH (MEMORY_OPTIMIZED = ON, DURABILITY = SCHEMA_ONLY)");
  });
  it("records each column mapping once, with notes for lossy types", () => {
    const spec = { tables: [t, { schema: "x", name: "y", columns: [{ name: "w", type: { kind: "datetime2" } }] }] } as unknown as ObjectSpec;
    const m = mappingsFor(spec);
    expect(m.map((x) => x.sqlServerType)).toEqual(["int NOT NULL", "nvarchar(100) NOT NULL", "decimal(18,2) NULL", "datetime2(7) NOT NULL"]);
    expect(m[3].notes).toMatch(/100 ns/);
  });
});

describe("vacuity guard", () => {
  it("rejects coverage below the minimum fraction", () => {
    expect(MIN_NON_EMPTY_FRACTION).toBe(0.3);
    expect(vacuityFailure(200, 59)).toMatch(/^vacuous: only 59\/200/);
    expect(vacuityFailure(200, 60)).toBeNull();
    expect(vacuityFailure(200, 200)).toBeNull();
  });
  it("does not judge a run with no random samples", () => {
    expect(vacuityFailure(0, 0)).toBeNull();
  });
});

describe("table-valued arguments", () => {
  const spec = {
    database: "X", schema: "Website", name: "P", objectClass: "procedure", windowParams: false, orderKey: [], pgFunction: "website.p", mutants: [],
    ssCall: "EXEC Website.P @List = ?, @By = ?",
    tables: [{
      schema: "Website", name: "L", tvp: { argIndex: 0 },
      columns: [{ name: "Id", type: { kind: "int" }, identity: true }, { name: "V", type: { kind: "nvarchar", n: 5 }, nullable: true }],
    }],
  } as unknown as ObjectSpec;
  it("SQL Server: fills a table variable one row at a time (identity left to the server), then passes it", () => {
    const r = withTableValuedArgs(spec, { tables: { "Website.L": [{ Id: 99, V: "a" }, { Id: 98, V: null }] } }, [7]);
    expect(r.ssSql).toBe(
      "DECLARE @tvp0 [Website].[L];\nINSERT INTO @tvp0 ([V]) VALUES (?);\nINSERT INTO @tvp0 ([V]) VALUES (?);\nEXEC Website.P @List = @tvp0, @By = ?"
    );
    expect(r.ssParams).toEqual(["a", null, 7]);
  });
  it("PostgreSQL: the same rows as JSON at the same position, identity numbered 1..n", () => {
    const r = withTableValuedArgs(spec, { tables: { "Website.L": [{ Id: 99, V: "a" }, { Id: 98, V: null }] } }, [7]);
    expect(r.pgParams).toEqual([JSON.stringify([{ Id: 1, V: "a" }, { Id: 2, V: null }]), 7]);
  });
  it("an empty list declares the variable and inserts nothing", () => {
    const r = withTableValuedArgs(spec, { tables: { "Website.L": [] } }, [7]);
    expect(r.ssSql).toBe("DECLARE @tvp0 [Website].[L];\nEXEC Website.P @List = @tvp0, @By = ?");
    expect(r.pgParams).toEqual(["[]", 7]);
  });
  it("refuses a call whose placeholders do not match the arguments", () => {
    expect(() => withTableValuedArgs(spec, { tables: { "Website.L": [] } }, [])).toThrow(/placeholders/);
  });
});
